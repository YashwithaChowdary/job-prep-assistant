"""Skills knowledge base.

One entry per skill: how it is written in the wild (aliases), what it implies,
which skills are close substitutes, how long it takes to learn, what to study,
a practice project and interview questions.

Relationship types (they are NOT the same thing):
  implies   - having skill A is strong evidence of skill B (pandas -> Python).
              Counted as a full match, flagged "implied".
  related   - a close substitute (AWS <-> Azure). Counted as a PARTIAL match (0.5).
  builds_on - prerequisites. Never earns credit, but shortens the learning plan.

Week estimates are rough, for part-time study (about 10 hours per week).
"""
